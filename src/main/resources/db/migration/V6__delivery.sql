-- =====================================================================
-- Доставка заказов студентами-курьерами.
--
--   deliveries                — одна доставка на заказ с адресом
--   delivery_issues           — проблемы по доставке (жалобы участников,
--                               автоматические — при блокировке кода)
--   delivery_status_history   — журнал смены статусов (пишет триггер)
--
-- Жизненный цикл (проверяется и в Java, и триггером ниже):
--
--   SEARCHING_COURIER ──► ASSIGNED ──► PICKED_UP ──► DELIVERED
--          ▲                 │             │
--          └─── курьер ──────┘             │
--               отказался / снят           │
--   любой незавершённый статус ────────────┴──────► CANCELLED
--
-- Подтверждение передачи — двумя одноразовыми кодами:
--   pickup_code   — курьер показывает заведению, заведение вводит его
--                   (заказ отдали именно назначенному курьеру);
--   delivery_code — клиент называет курьеру при получении, курьер вводит
--                   (заказ действительно получил клиент).
-- Коды хранятся зашифрованными (AES-256-GCM, как TOTP-секреты),
-- после исчерпания попыток ввода код блокируется до решения администратора.
-- =====================================================================

CREATE TABLE deliveries
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id               BIGINT         NOT NULL,
    courier_id             BIGINT,
    status                 VARCHAR(20)    NOT NULL DEFAULT 'SEARCHING_COURIER',
    courier_fee            NUMERIC(12, 2) NOT NULL,
    delivery_code          VARCHAR(255)   NOT NULL,
    pickup_code            VARCHAR(255),
    delivery_code_attempts INTEGER        NOT NULL DEFAULT 0,
    pickup_code_attempts   INTEGER        NOT NULL DEFAULT 0,
    admin_note             VARCHAR(600),
    created_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    assigned_at            TIMESTAMPTZ,
    picked_up_at           TIMESTAMPTZ,
    delivered_at           TIMESTAMPTZ,
    cancelled_at           TIMESTAMPTZ,
    updated_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version                BIGINT         NOT NULL DEFAULT 0,

    CONSTRAINT pk_deliveries PRIMARY KEY (id),
    CONSTRAINT uq_deliveries_order UNIQUE (order_id),
    CONSTRAINT fk_deliveries_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_deliveries_courier FOREIGN KEY (courier_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_deliveries_status CHECK (status IN
                                           ('SEARCHING_COURIER', 'ASSIGNED', 'PICKED_UP', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_deliveries_courier_fee CHECK (courier_fee >= 0),
    CONSTRAINT ck_deliveries_attempts CHECK (delivery_code_attempts >= 0 AND pickup_code_attempts >= 0),
    -- Пока курьер не найден, его нет; с момента назначения и до доставки — есть
    CONSTRAINT ck_deliveries_courier_presence CHECK (
        (status = 'SEARCHING_COURIER' AND courier_id IS NULL)
            OR (status IN ('ASSIGNED', 'PICKED_UP', 'DELIVERED') AND courier_id IS NOT NULL)
            OR status = 'CANCELLED'
        ),
    CONSTRAINT ck_deliveries_pickup_code CHECK (status <> 'ASSIGNED' OR pickup_code IS NOT NULL),
    CONSTRAINT ck_deliveries_delivered_at CHECK (status <> 'DELIVERED' OR delivered_at IS NOT NULL),
    CONSTRAINT ck_deliveries_cancelled_at CHECK (status <> 'CANCELLED' OR cancelled_at IS NOT NULL)
);

COMMENT ON TABLE deliveries IS 'Доставка заказа студентом-курьером (одна на заказ с адресом)';
COMMENT ON COLUMN deliveries.courier_fee IS 'Сколько получает курьер за доставку (фиксируется при создании)';
COMMENT ON COLUMN deliveries.delivery_code IS 'Код клиента для курьера, зашифрован AES-256-GCM';
COMMENT ON COLUMN deliveries.pickup_code IS 'Код курьера для заведения, зашифрован AES-256-GCM; выдаётся при назначении';
COMMENT ON COLUMN deliveries.delivery_code_attempts IS 'Неверные вводы кода клиента; при лимите код блокируется';
COMMENT ON COLUMN deliveries.pickup_code_attempts IS 'Неверные вводы кода курьера; при лимите код блокируется';
COMMENT ON COLUMN deliveries.admin_note IS 'Последнее действие администратора и его причина';
COMMENT ON COLUMN deliveries.version IS 'Оптимистическая блокировка: два курьера не возьмут один заказ';

-- Лента свободных заказов для курьеров
CREATE INDEX ix_deliveries_searching ON deliveries (created_at) WHERE status = 'SEARCHING_COURIER';
-- «Мои доставки» и заработок курьера + FK
CREATE INDEX ix_deliveries_courier_status ON deliveries (courier_id, status);
-- Админка: фильтр по статусу
CREATE INDEX ix_deliveries_status_created ON deliveries (status, created_at DESC);

CREATE TRIGGER trg_deliveries_updated_at
    BEFORE UPDATE ON deliveries
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- ---------------------------------------------------------------------
-- Проверка переходов статуса доставки
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_delivery_status_transition()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
BEGIN
    IF NEW.status = OLD.status THEN
        RETURN NEW;
    END IF;

    IF NOT (
        (OLD.status = 'SEARCHING_COURIER' AND NEW.status IN ('ASSIGNED', 'CANCELLED')) OR
        (OLD.status = 'ASSIGNED' AND NEW.status IN ('SEARCHING_COURIER', 'PICKED_UP', 'CANCELLED')) OR
        (OLD.status = 'PICKED_UP' AND NEW.status IN ('DELIVERED', 'CANCELLED'))
        ) THEN
        RAISE EXCEPTION 'Недопустимый переход статуса доставки #%: % -> %', OLD.id, OLD.status, NEW.status
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_deliveries_status_transition
    BEFORE UPDATE OF status ON deliveries
    FOR EACH ROW EXECUTE FUNCTION check_delivery_status_transition();


-- ---------------------------------------------------------------------
-- Журнал статусов доставки: кто и когда вёл заказ (для разбора споров)
-- ---------------------------------------------------------------------
CREATE TABLE delivery_status_history
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    delivery_id BIGINT      NOT NULL,
    old_status  VARCHAR(20),
    new_status  VARCHAR(20) NOT NULL,
    courier_id  BIGINT,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_delivery_status_history PRIMARY KEY (id),
    CONSTRAINT fk_dsh_delivery FOREIGN KEY (delivery_id)
        REFERENCES deliveries (id) ON DELETE CASCADE
);

CREATE INDEX ix_dsh_delivery_changed ON delivery_status_history (delivery_id, changed_at);

COMMENT ON TABLE delivery_status_history IS 'Журнал смены статусов доставки (заполняется триггером)';
COMMENT ON COLUMN delivery_status_history.courier_id IS 'Курьер на момент смены статуса (без FK: журнал не мешает удалять пользователей)';

CREATE OR REPLACE FUNCTION log_delivery_status_change()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO delivery_status_history (delivery_id, old_status, new_status, courier_id)
        VALUES (NEW.id, NULL, NEW.status, NEW.courier_id);
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO delivery_status_history (delivery_id, old_status, new_status, courier_id)
        VALUES (NEW.id, OLD.status, NEW.status, coalesce(NEW.courier_id, OLD.courier_id));
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_deliveries_status_log
    AFTER INSERT OR UPDATE OF status ON deliveries
    FOR EACH ROW EXECUTE FUNCTION log_delivery_status_change();


-- ---------------------------------------------------------------------
-- delivery_issues — проблемы по доставке, их решает администратор
-- ---------------------------------------------------------------------
CREATE TABLE delivery_issues
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    delivery_id    BIGINT        NOT NULL,
    reporter_id    BIGINT,
    reported_by    VARCHAR(20)   NOT NULL,
    type           VARCHAR(30)   NOT NULL,
    description    VARCHAR(1000),
    status         VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    resolution     VARCHAR(1000),
    resolved_by_id BIGINT,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    resolved_at    TIMESTAMPTZ,

    CONSTRAINT pk_delivery_issues PRIMARY KEY (id),
    CONSTRAINT fk_delivery_issues_delivery FOREIGN KEY (delivery_id)
        REFERENCES deliveries (id) ON DELETE CASCADE,
    CONSTRAINT fk_delivery_issues_reporter FOREIGN KEY (reporter_id)
        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_delivery_issues_resolved_by FOREIGN KEY (resolved_by_id)
        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_delivery_issues_reported_by CHECK (reported_by IN ('CUSTOMER', 'COURIER', 'VENUE', 'SYSTEM')),
    CONSTRAINT ck_delivery_issues_type CHECK (type IN
                                              ('NOT_DELIVERED', 'COURIER_NOT_ARRIVED', 'CUSTOMER_UNREACHABLE',
                                               'CUSTOMER_REFUSES_CODE', 'DAMAGED_OR_WRONG', 'CODE_LOCKED', 'OTHER')),
    CONSTRAINT ck_delivery_issues_status CHECK (status IN ('OPEN', 'RESOLVED')),
    CONSTRAINT ck_delivery_issues_resolution CHECK (
        (status = 'OPEN' AND resolved_at IS NULL)
            OR (status = 'RESOLVED' AND resolved_at IS NOT NULL AND btrim(coalesce(resolution, '')) <> '')
        )
);

COMMENT ON TABLE delivery_issues IS 'Проблемы по доставке: жалобы участников и автоматические (блокировка кода)';
COMMENT ON COLUMN delivery_issues.reporter_id IS 'Кто сообщил; NULL — создано системой';
COMMENT ON COLUMN delivery_issues.reported_by IS 'Роль сообщившего в этой доставке: CUSTOMER, COURIER, VENUE, SYSTEM';

CREATE INDEX ix_delivery_issues_status_created ON delivery_issues (status, created_at DESC);
CREATE INDEX ix_delivery_issues_delivery ON delivery_issues (delivery_id);
CREATE INDEX ix_delivery_issues_reporter ON delivery_issues (reporter_id);
CREATE INDEX ix_delivery_issues_resolved_by ON delivery_issues (resolved_by_id);
