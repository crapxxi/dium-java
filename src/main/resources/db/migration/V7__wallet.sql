-- =====================================================================
-- Кошелёк баллов.
--
--   wallets              — баланс пользователя (одна строка на пользователя)
--   wallet_transactions  — журнал операций: каждое начисление и списание
--
-- Правила:
--   * 1 балл = 1 ₸ дохода курьера: за доставку курьер получает столько баллов,
--     сколько клиент заплатил за неё в тенге;
--   * баллами можно оплатить заказ целиком, цена в баллах выше цены в тенге
--     на наценку (wallet.points-markup-percent, по умолчанию 20%);
--   * баллы не выводятся в деньги и не переводятся другим пользователям;
--   * баланс не бывает отрицательным (CHECK), журнал только дописывается
--     (UPDATE и прямой DELETE запрещены триггером);
--   * у каждой автоматической операции есть ключ идемпотентности: одна и та же
--     доставка не оплачивается курьеру дважды, один заказ не списывается дважды.
-- =====================================================================

CREATE TABLE wallets
(
    user_id    BIGINT      NOT NULL,
    balance    BIGINT      NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_wallets PRIMARY KEY (user_id),
    CONSTRAINT fk_wallets_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_wallets_balance CHECK (balance >= 0)
);

COMMENT ON TABLE wallets IS 'Баланс баллов пользователя; меняется только вместе с записью в wallet_transactions';

CREATE TRIGGER trg_wallets_updated_at
    BEFORE UPDATE ON wallets
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


CREATE TABLE wallet_transactions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT       NOT NULL,
    amount          BIGINT       NOT NULL,
    balance_after   BIGINT       NOT NULL,
    type            VARCHAR(30)  NOT NULL,
    -- Ссылки без FK: журнал не должен мешать удалению заказов и не должен меняться при нём
    order_id        BIGINT,
    delivery_id     BIGINT,
    idempotency_key VARCHAR(100),
    note            VARCHAR(600),
    created_by_id   BIGINT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT pk_wallet_transactions PRIMARY KEY (id),
    CONSTRAINT fk_wallet_transactions_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_wallet_transactions_key UNIQUE (idempotency_key),
    CONSTRAINT ck_wallet_transactions_amount CHECK (amount <> 0),
    CONSTRAINT ck_wallet_transactions_balance CHECK (balance_after >= 0),
    CONSTRAINT ck_wallet_transactions_type CHECK (type IN
                                                  ('DELIVERY_EARNING', 'ORDER_PAYMENT', 'ORDER_REFUND',
                                                   'ADMIN_ADJUSTMENT')),
    -- Ручная правка администратора — только с причиной и автором
    CONSTRAINT ck_wallet_transactions_adjustment CHECK (
        type <> 'ADMIN_ADJUSTMENT' OR (created_by_id IS NOT NULL AND btrim(coalesce(note, '')) <> '')
        )
);

COMMENT ON TABLE wallet_transactions IS 'Журнал операций с баллами (только дописывается)';
COMMENT ON COLUMN wallet_transactions.amount IS 'Плюс — начисление, минус — списание';
COMMENT ON COLUMN wallet_transactions.balance_after IS 'Баланс после операции';
COMMENT ON COLUMN wallet_transactions.idempotency_key IS 'Ключ автоматической операции, например delivery-earning:15';
COMMENT ON COLUMN wallet_transactions.created_by_id IS 'Администратор, сделавший ручную правку (без FK, как и ссылки на заказ)';

CREATE INDEX ix_wallet_transactions_user ON wallet_transactions (user_id, id DESC);
CREATE INDEX ix_wallet_transactions_order ON wallet_transactions (order_id) WHERE order_id IS NOT NULL;

-- Журнал нельзя исправить задним числом. Удаление разрешено только каскадом
-- вместе с пользователем (тогда триггер срабатывает внутри FK-триггера, глубина > 1).
CREATE OR REPLACE FUNCTION forbid_wallet_transaction_change()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
BEGIN
    IF TG_OP = 'DELETE' AND pg_trigger_depth() > 1 THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'Журнал баллов только дописывается: % запрещён', TG_OP
        USING ERRCODE = 'check_violation';
END;
$$;

CREATE TRIGGER trg_wallet_transactions_append_only
    BEFORE UPDATE OR DELETE ON wallet_transactions
    FOR EACH ROW EXECUTE FUNCTION forbid_wallet_transaction_change();


-- ---------------------------------------------------------------------
-- Оплата заказа баллами
-- ---------------------------------------------------------------------
ALTER TABLE orders
    ADD COLUMN payment_method  VARCHAR(10) NOT NULL DEFAULT 'KASPI',
    ADD COLUMN points_spent    BIGINT,
    ADD COLUMN points_delivery BIGINT;

ALTER TABLE orders
    ADD CONSTRAINT ck_orders_payment_method CHECK (payment_method IN ('KASPI', 'POINTS')),
    ADD CONSTRAINT ck_orders_points CHECK (
        (payment_method = 'KASPI' AND points_spent IS NULL AND points_delivery IS NULL)
            OR (payment_method = 'POINTS' AND points_spent > 0
            AND points_delivery IS NOT NULL AND points_delivery BETWEEN 0 AND points_spent)
        );

-- Плательщик Kaspi не нужен, если заказ оплачен баллами
ALTER TABLE orders ALTER COLUMN payment_from DROP NOT NULL;
ALTER TABLE orders DROP CONSTRAINT ck_orders_payment_from_not_blank;
ALTER TABLE orders
    ADD CONSTRAINT ck_orders_payment_from_not_blank CHECK (
        payment_method = 'POINTS' OR (payment_from IS NOT NULL AND btrim(payment_from) <> '')
        );

COMMENT ON COLUMN orders.payment_method IS 'KASPI — перевод заведению, POINTS — оплачено баллами';
COMMENT ON COLUMN orders.points_spent IS 'Сколько баллов списано за заказ (с наценкой)';
COMMENT ON COLUMN orders.points_delivery IS 'Часть points_spent за доставку: возвращается, если доставку отменили';
