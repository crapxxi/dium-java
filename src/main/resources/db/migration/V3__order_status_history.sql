-- =====================================================================
-- Жизненный цикл заказа на уровне БД:
--   1. Проверка допустимых переходов статуса (защита от багов в коде
--      и ручных правок).
--   2. Журнал смены статусов — когда заказ приняли / приготовили / выдали.
--      Пишется триггером, поэтому Java-код менять не нужно.
--
--   Статусы хранятся как ORDINAL (см. V1, order_status_name()):
--   0 PENDING ──► 1 PREPARING ──► 2 READY ──► 3 COMPLETED
--      │
--      └──────► 4 CANCELLED
-- =====================================================================

CREATE TABLE order_status_history
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id   BIGINT      NOT NULL,
    old_status SMALLINT,
    new_status SMALLINT    NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_order_status_history PRIMARY KEY (id),
    CONSTRAINT fk_osh_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_osh_old_status CHECK (old_status IS NULL OR old_status BETWEEN 0 AND 4),
    CONSTRAINT ck_osh_new_status CHECK (new_status BETWEEN 0 AND 4)
);

CREATE INDEX ix_osh_order_changed ON order_status_history (order_id, changed_at);

COMMENT ON TABLE order_status_history IS 'Журнал смены статусов заказа (заполняется триггером)';
COMMENT ON COLUMN order_status_history.old_status IS 'OrderStatus (ORDINAL); NULL — заказ только что создан';
COMMENT ON COLUMN order_status_history.new_status IS 'OrderStatus (ORDINAL)';


-- ---------------------------------------------------------------------
-- Проверка переходов статуса
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_order_status_transition()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
BEGIN
    IF NEW.status = OLD.status THEN
        RETURN NEW;
    END IF;

    IF NOT (
        (OLD.status = 0 AND NEW.status IN (1, 4)) OR -- PENDING   -> PREPARING | CANCELLED
        (OLD.status = 1 AND NEW.status = 2) OR       -- PREPARING -> READY
        (OLD.status = 2 AND NEW.status = 3)          -- READY     -> COMPLETED
        ) THEN
        RAISE EXCEPTION 'Недопустимый переход статуса заказа #%: % -> %',
            OLD.id, order_status_name(OLD.status), order_status_name(NEW.status)
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_orders_status_transition
    BEFORE UPDATE OF status ON orders
    FOR EACH ROW EXECUTE FUNCTION check_order_status_transition();


-- ---------------------------------------------------------------------
-- Журналирование статусов
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION log_order_status_change()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO order_status_history (order_id, old_status, new_status)
        VALUES (NEW.id, NULL, NEW.status);
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO order_status_history (order_id, old_status, new_status)
        VALUES (NEW.id, OLD.status, NEW.status);
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_orders_status_log
    AFTER INSERT OR UPDATE OF status ON orders
    FOR EACH ROW EXECUTE FUNCTION log_order_status_change();
