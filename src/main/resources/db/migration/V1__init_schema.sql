-- =====================================================================
-- DIUM — базовая схема БД
--
-- Принципы:
--   * Имена колонок совпадают с JPA-сущностями (CamelCase -> snake_case),
--     Hibernate работает в режиме ddl-auto=validate.
--   * Все инварианты, которые не должны нарушаться ни при каких условиях,
--     продублированы на уровне БД (NOT NULL, CHECK, UNIQUE, FK).
--   * Enum'ы хранятся так же, как их маппит сущность:
--       users.role        — строкой (@Enumerated(EnumType.STRING));
--       orders.status,
--       products.category — порядковым номером (ORDINAL, без @Enumerated).
--     Для ORDINAL-колонок CHECK ограничивает диапазон, а функции
--     order_status_name() / product_category_name() дают читаемое имя.
--     ВАЖНО: новые значения в OrderStatus/ProductCategory добавлять
--     только в КОНЕЦ enum'а, иначе номера в БД сместятся.
--   * Удаление данных, на которые ссылается история заказов, запрещено
--     (ON DELETE RESTRICT): продукты и группы модификаторов удаляются мягко.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Служебная функция: автоматическое обновление updated_at
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION set_updated_at() IS 'BEFORE UPDATE триггер: проставляет updated_at = now()';


-- ---------------------------------------------------------------------
-- Расшифровка ORDINAL-enum'ов (порядок = порядок констант в Java)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION order_status_name(p_status SMALLINT)
    RETURNS TEXT
    LANGUAGE sql
    IMMUTABLE
AS
$$
SELECT (ARRAY ['PENDING', 'PREPARING', 'READY', 'COMPLETED', 'CANCELLED'])[p_status + 1];
$$;

COMMENT ON FUNCTION order_status_name(SMALLINT) IS 'Номер OrderStatus -> имя (порядок констант com.dium.demo.enums.OrderStatus)';

CREATE OR REPLACE FUNCTION product_category_name(p_category SMALLINT)
    RETURNS TEXT
    LANGUAGE sql
    IMMUTABLE
AS
$$
SELECT (ARRAY ['FOOD', 'DRINK'])[p_category + 1];
$$;

COMMENT ON FUNCTION product_category_name(SMALLINT) IS 'Номер ProductCategory -> имя (порядок констант com.dium.demo.enums.ProductCategory)';


-- ---------------------------------------------------------------------
-- users — пользователи (клиенты, владельцы заведений, администраторы)
-- ---------------------------------------------------------------------
CREATE TABLE users
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    phone        VARCHAR(20)  NOT NULL,
    name         VARCHAR(100) NOT NULL,
    password     VARCHAR(100) NOT NULL,
    role         VARCHAR(20)  NOT NULL DEFAULT 'CLIENT',
    payment_from VARCHAR(100),
    is_confirmed BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_phone UNIQUE (phone),
    CONSTRAINT ck_users_phone_not_blank CHECK (btrim(phone) <> ''),
    CONSTRAINT ck_users_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_users_role CHECK (role IN ('CLIENT', 'VENUE_OWNER', 'ADMIN'))
);

COMMENT ON TABLE users IS 'Пользователи системы. Логин — номер телефона';
COMMENT ON COLUMN users.password IS 'BCrypt-хэш пароля';
COMMENT ON COLUMN users.payment_from IS 'Имя/номер плательщика в Kaspi по умолчанию';
COMMENT ON COLUMN users.is_confirmed IS 'Телефон подтверждён через OTP в WhatsApp; без этого аккаунт заблокирован';


-- ---------------------------------------------------------------------
-- venues — заведения (кафе/буфеты). У заведения ровно один владелец
-- ---------------------------------------------------------------------
CREATE TABLE venues
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_id       BIGINT         NOT NULL,
    name           VARCHAR(150)   NOT NULL,
    description    TEXT,
    address        VARCHAR(255),
    image_url      VARCHAR(512),
    can_deliver    BOOLEAN        NOT NULL DEFAULT FALSE,
    delivery_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    kaspi_url      VARCHAR(512),
    is_working     BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_venues PRIMARY KEY (id),
    CONSTRAINT uq_venues_owner UNIQUE (owner_id),
    CONSTRAINT fk_venues_owner FOREIGN KEY (owner_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_venues_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_venues_delivery_price CHECK (delivery_price >= 0)
);

COMMENT ON TABLE venues IS 'Заведения общепита в университете';
COMMENT ON COLUMN venues.kaspi_url IS 'Ссылка на оплату через Kaspi';
COMMENT ON COLUMN venues.is_working IS 'Принимает ли заведение заказы прямо сейчас';


-- ---------------------------------------------------------------------
-- products — позиции меню
-- ---------------------------------------------------------------------
CREATE TABLE products
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    venue_id      BIGINT         NOT NULL,
    name          VARCHAR(150)   NOT NULL,
    description   TEXT,
    price         NUMERIC(12, 2) NOT NULL,
    category      SMALLINT       NOT NULL,
    image_url     VARCHAR(512),
    in_stock      BOOLEAN        NOT NULL DEFAULT FALSE,
    has_modifiers BOOLEAN        NOT NULL DEFAULT FALSE,
    deleted       BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT fk_products_venue FOREIGN KEY (venue_id)
        REFERENCES venues (id) ON DELETE CASCADE,
    CONSTRAINT ck_products_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_category CHECK (category BETWEEN 0 AND 1)
);

COMMENT ON TABLE products IS 'Позиции меню заведения';
COMMENT ON COLUMN products.category IS 'ProductCategory (ORDINAL): 0=FOOD, 1=DRINK';
COMMENT ON COLUMN products.deleted IS 'Мягкое удаление: товар остаётся в истории заказов';


-- ---------------------------------------------------------------------
-- modifier_groups — группы опций к продукту ("Соусы", "Размер")
-- ---------------------------------------------------------------------
CREATE TABLE modifier_groups
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id  BIGINT       NOT NULL,
    name        VARCHAR(100) NOT NULL,
    is_required BOOLEAN      NOT NULL DEFAULT FALSE,
    min_choices INTEGER,
    max_choices INTEGER,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT pk_modifier_groups PRIMARY KEY (id),
    CONSTRAINT fk_modifier_groups_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT ck_modifier_groups_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_modifier_groups_min_choices CHECK (min_choices IS NULL OR min_choices >= 0),
    CONSTRAINT ck_modifier_groups_max_choices CHECK (max_choices IS NULL OR max_choices >= 1),
    CONSTRAINT ck_modifier_groups_choices_range CHECK (
        min_choices IS NULL OR max_choices IS NULL OR min_choices <= max_choices
        )
);

COMMENT ON TABLE modifier_groups IS 'Группы модификаторов продукта';
COMMENT ON COLUMN modifier_groups.is_deleted IS 'Мягкое удаление группы';


-- ---------------------------------------------------------------------
-- modifiers — конкретная опция с наценкой
-- ---------------------------------------------------------------------
CREATE TABLE modifiers
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    modifier_group_id BIGINT         NOT NULL,
    name              VARCHAR(100)   NOT NULL,
    price_delta       NUMERIC(12, 2) NOT NULL DEFAULT 0,
    in_stock          BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_modifiers PRIMARY KEY (id),
    CONSTRAINT fk_modifiers_group FOREIGN KEY (modifier_group_id)
        REFERENCES modifier_groups (id) ON DELETE CASCADE,
    CONSTRAINT ck_modifiers_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_modifiers_price_delta CHECK (price_delta >= 0)
);

COMMENT ON TABLE modifiers IS 'Опции внутри группы модификаторов';
COMMENT ON COLUMN modifiers.price_delta IS 'Наценка к цене продукта';


-- ---------------------------------------------------------------------
-- orders — заказы
-- ---------------------------------------------------------------------
CREATE TABLE orders
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT         NOT NULL,
    venue_id     BIGINT         NOT NULL,
    status       SMALLINT       NOT NULL DEFAULT 0,
    address      VARCHAR(255),
    comment      VARCHAR(1000),
    delivery_fee NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_sum    NUMERIC(12, 2) NOT NULL,
    pickup_code  INTEGER,
    payment_from VARCHAR(100)   NOT NULL,
    -- TIMESTAMP (без зоны) — поле маппится на LocalDateTime в сущности Order
    created_at   TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_venue FOREIGN KEY (venue_id)
        REFERENCES venues (id) ON DELETE RESTRICT,
    CONSTRAINT ck_orders_status CHECK (status BETWEEN 0 AND 4),
    CONSTRAINT ck_orders_delivery_fee CHECK (delivery_fee >= 0),
    CONSTRAINT ck_orders_total_sum CHECK (total_sum > 0),
    CONSTRAINT ck_orders_pickup_code CHECK (pickup_code IS NULL OR pickup_code BETWEEN 1000 AND 9999),
    CONSTRAINT ck_orders_payment_from_not_blank CHECK (btrim(payment_from) <> '')
);

COMMENT ON TABLE orders IS 'Заказы клиентов';
COMMENT ON COLUMN orders.status IS 'OrderStatus (ORDINAL): 0=PENDING, 1=PREPARING, 2=READY, 3=COMPLETED, 4=CANCELLED';
COMMENT ON COLUMN orders.address IS 'Адрес доставки; NULL — самовывоз';
COMMENT ON COLUMN orders.pickup_code IS '4-значный код выдачи; проставляется сразу после INSERT';
COMMENT ON COLUMN orders.payment_from IS 'Имя/номер плательщика в Kaspi для сверки оплаты';


-- ---------------------------------------------------------------------
-- order_items — строки заказа (цена фиксируется на момент покупки)
-- ---------------------------------------------------------------------
CREATE TABLE order_items
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id          BIGINT         NOT NULL,
    product_id        BIGINT         NOT NULL,
    count             INTEGER        NOT NULL,
    price_at_purchase NUMERIC(12, 2) NOT NULL,

    CONSTRAINT pk_order_items PRIMARY KEY (id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT ck_order_items_count CHECK (count > 0),
    CONSTRAINT ck_order_items_price CHECK (price_at_purchase >= 0)
);

COMMENT ON TABLE order_items IS 'Позиции заказа';
COMMENT ON COLUMN order_items.price_at_purchase IS 'Цена единицы с модификаторами на момент заказа';


-- ---------------------------------------------------------------------
-- order_item_modifiers — выбранные модификаторы позиции (M:N)
-- ---------------------------------------------------------------------
CREATE TABLE order_item_modifiers
(
    order_item_id BIGINT NOT NULL,
    modifier_id   BIGINT NOT NULL,

    CONSTRAINT pk_order_item_modifiers PRIMARY KEY (order_item_id, modifier_id),
    CONSTRAINT fk_oim_order_item FOREIGN KEY (order_item_id)
        REFERENCES order_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_oim_modifier FOREIGN KEY (modifier_id)
        REFERENCES modifiers (id) ON DELETE RESTRICT
);

COMMENT ON TABLE order_item_modifiers IS 'Связь позиции заказа с выбранными модификаторами';


-- ---------------------------------------------------------------------
-- Триггеры updated_at
-- ---------------------------------------------------------------------
CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_venues_updated_at
    BEFORE UPDATE ON venues
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_products_updated_at
    BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_modifier_groups_updated_at
    BEFORE UPDATE ON modifier_groups
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_modifiers_updated_at
    BEFORE UPDATE ON modifiers
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_orders_updated_at
    BEFORE UPDATE ON orders
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
