package com.dium.demo.enums;

/** Как покупатель получает заказ. Выбирает сам покупатель при оформлении. */
public enum FulfillmentType {
    /** Сам забирает в заведении: заказ не попадает в ленту курьеров. */
    PICKUP,
    /** Привозит студент-курьер: после того как заведение примет заказ, он появляется в ленте курьеров. */
    DELIVERY
}
