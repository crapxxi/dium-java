package com.dium.demo.services.order;

/**
 * Способ оплаты заказа. Контроллер зависит только от этого интерфейса, поэтому другую
 * платёжную систему можно подключить новой реализацией, не меняя остальной код.
 */
public interface PaymentService {
    /** Проведение оплаты. Задел на будущее: для платёжных систем, где оплату инициирует сервер. */
    void pay();

    /** @return ссылка, по которой клиент оплачивает заказ */
    String getPaymentUrl(Long orderId);
}
